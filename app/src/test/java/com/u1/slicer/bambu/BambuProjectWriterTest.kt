    @Test
    fun `writer packages every supported bambu identity and machine filament profile`() {
        val expected = mapOf(
            SlicerTarget.BambuX1C to Triple("BL-P001", "Bambu Lab X1 Carbon", "Bambu PLA Basic @BBL X1C"),
            SlicerTarget.BambuX1E to Triple("C13", "Bambu Lab X1E", "Bambu PLA Basic @BBL X1C"),
            SlicerTarget.BambuP1S to Triple("C12", "Bambu Lab P1S", "Bambu PLA Basic @BBL X1C"),
            SlicerTarget.BambuP1P to Triple("C11", "Bambu Lab P1P", "Bambu PLA Basic @BBL X1"),
            SlicerTarget.BambuP2S to Triple("GM049", "Bambu Lab P2S", "Bambu PLA Basic @BBL P2S"),
            SlicerTarget.BambuA1 to Triple("N2S", "Bambu Lab A1", "Bambu PLA Basic @BBL A1"),
            SlicerTarget.BambuA1Mini to Triple("N1", "Bambu Lab A1 mini", "Bambu PLA Basic @BBL A1M"),
            SlicerTarget.BambuH2D to Triple("O1D", "Bambu Lab H2D", "Bambu PLA Basic @BBL H2D"),
        )

        expected.forEach { (target, identity) ->
            val gcode = File(tmp.root, "${target.name}.gcode").apply { writeText("G28\n") }
            val out = File(tmp.root, "${target.name}.gcode.3mf")
            BambuProjectWriter.writeSinglePlateProject(
                outputFile = out,
                gcodeFile = gcode,
                modelName = target.name,
                plateId = 1,
                filamentColours = listOf("#FFFFFF"),
                filamentTypes = listOf("PLA"),
                target = target,
            )

            ZipFile(out).use { zip ->
                val settings = JSONObject(
                    zip.getInputStream(zip.getEntry("Metadata/project_settings.config")).reader().readText(),
                )
                assertEquals(identity.first, settings.getString("printer_model_id"))
                assertEquals(identity.second, settings.getString("printer_model"))
                assertEquals(
                    identity.third,
                    settings.getJSONArray("filament_settings_id").getString(0),
                )
            }
        }
    }

