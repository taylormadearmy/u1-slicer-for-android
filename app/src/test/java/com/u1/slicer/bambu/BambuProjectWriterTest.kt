    @Test
    fun `writer moves native eof config before executable block`() {
        val gcode = tmp.newFile("native-layout.gcode").apply {
            writeText(
                """
                ; HEADER_BLOCK_START
                ; generated by test
                ; HEADER_BLOCK_END
                ; thumbnail begin 1x1 4
                ; AAAA
                ; thumbnail end
                ; EXECUTABLE_BLOCK_START
                G28
                ; EXECUTABLE_BLOCK_END
                ; CONFIG_BLOCK_START
                ; printer_model = Bambu Lab A1 mini
                ; CONFIG_BLOCK_END
                """.trimIndent(),
            )
        }
        val out = File(tmp.root, "native-layout.3mf")

        BambuProjectWriter.writeSinglePlateProject(
            outputFile = out,
            gcodeFile = gcode,
            modelName = "cube",
            plateId = 1,
            filamentColours = listOf("#FFFFFF"),
            filamentTypes = listOf("PLA"),
        )

        ZipFile(out).use { zip ->
            val packaged = zip.getInputStream(zip.getEntry("Metadata/plate_1.gcode"))
                .reader()
                .readText()
            assertTrue(packaged.indexOf("; HEADER_BLOCK_END") < packaged.indexOf("; CONFIG_BLOCK_START"))
            assertTrue(packaged.indexOf("; CONFIG_BLOCK_END") < packaged.indexOf("; EXECUTABLE_BLOCK_START"))
            assertTrue(!packaged.contains("; thumbnail begin"))
            val expectedMd5 = java.security.MessageDigest.getInstance("MD5")
                .digest(packaged.toByteArray())
                .joinToString("") { "%02x".format(it) }
            assertEquals(
                expectedMd5,
                zip.getInputStream(zip.getEntry("Metadata/plate_1.gcode.md5"))
                    .reader()
                    .readText()
                    .lowercase(),
            )
        }
    }

