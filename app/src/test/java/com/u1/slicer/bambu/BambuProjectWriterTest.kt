    @Test
    fun `writer records real sliced bounds time and filament usage`() {
        val gcode = tmp.newFile("measured.gcode").apply {
            writeText(
                """
                ; max_z_height: 10.00
                ; CONFIG_BLOCK_START
                ; layer_height = 0.2
                ; curr_bed_type = Textured PEI Plate
                ; CONFIG_BLOCK_END
                EXCLUDE_OBJECT_DEFINE NAME=cube CENTER=90,90 POLYGON=[[85,85],[95,85],[95,95],[85,95]]
                ;LAYER_CHANGE
                G0 X84 Y84
                G1 X96 Y84 E0.5
                G1 X96 Y96 E0.5
                ;LAYER_CHANGE
                ; filament used [mm] = 4241.66
                ; filament used [g] = 12.85
                ; estimated printing time (normal mode) = 1h 44m 23s
                """.trimIndent(),
            )
        }
        val out = File(tmp.root, "measured.gcode.3mf")

        BambuProjectWriter.writeSinglePlateProject(
            outputFile = out,
            gcodeFile = gcode,
            modelName = "cube",
            plateId = 1,
            filamentColours = listOf("#FFFFFF"),
            filamentTypes = listOf("PLA"),
        )

        ZipFile(out).use { zip ->
            val plate = JSONObject(
                zip.getInputStream(zip.getEntry("Metadata/plate_1.json")).reader().readText(),
            )
            assertEquals(84.0, plate.getJSONArray("bbox_all").getDouble(0), 0.0001)
            assertEquals(96.0, plate.getJSONArray("bbox_all").getDouble(3), 0.0001)
            assertEquals("textured_plate", plate.getString("bed_type"))
            assertTrue(plate.getJSONArray("bbox_objects").getJSONObject(0).getDouble("area") > 0.0)

            val sliceInfo = zip.getInputStream(zip.getEntry("Metadata/slice_info.config"))
                .reader().readText()
            assertTrue(sliceInfo.contains("key=\"prediction\" value=\"6263\""))
            assertTrue(sliceInfo.contains("key=\"weight\" value=\"12.85\""))
            assertTrue(sliceInfo.contains("used_m=\"4.2417\""))
            assertTrue(sliceInfo.contains("used_g=\"12.85\""))

            val model = zip.getInputStream(zip.getEntry("3D/3dmodel.model")).reader().readText()
            assertTrue(model.contains(" 90 90 0\" printable=\"1\""))
            val objectModel = zip.getInputStream(zip.getEntry("3D/Objects/object_1.model"))
                .reader().readText()
            assertTrue(objectModel.contains("x=\"-5\""))
            assertTrue(objectModel.contains("z=\"10\""))
        }
    }

    @Test
    fun `writer atomically replaces an existing project and removes staging file`() {
        val gcode = tmp.newFile("atomic.gcode").apply { writeText("G28\n") }
        val out = File(tmp.root, "atomic.gcode.3mf").apply { writeText("old-incomplete-project") }

        BambuProjectWriter.writeSinglePlateProject(
            outputFile = out,
            gcodeFile = gcode,
            modelName = "atomic",
            plateId = 1,
            filamentColours = listOf("#FFFFFF"),
            filamentTypes = listOf("PLA"),
        )

        ZipFile(out).use { zip ->
            assertNotNull(zip.getEntry("Metadata/plate_1.gcode"))
        }
        assertTrue(
            tmp.root.listFiles().orEmpty().none {
                it.name.startsWith(".${out.name}.") && it.name.endsWith(".tmp")
            },
        )
    }

